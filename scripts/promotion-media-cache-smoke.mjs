import http from "node:http";

const ORIGIN = "http://localhost:5173";
const PASSWORD = "CoffeeBeans2026";
const STAMP = Date.now();

function rawRequest(method, path, headers, bodyString) {
	return new Promise((resolve, reject) => {
		const target = new URL(`${ORIGIN}${path}`);
		const req = http.request(
			{
				method,
				hostname: target.hostname,
				port: target.port,
				path: `${target.pathname}${target.search}`,
				headers,
				agent: false,
			},
			(res) => {
				const chunks = [];
				res.on("data", (chunk) => chunks.push(chunk));
				res.on("end", () => {
					resolve({
						status: res.statusCode,
						headers: res.headers,
						body: Buffer.concat(chunks).toString("utf8"),
					});
				});
			},
		);
		req.on("error", reject);
		if (bodyString !== undefined) req.write(bodyString);
		req.end();
	});
}

class Session {
	constructor() {
		this.cookies = {};
	}

	cookieHeader() {
		return Object.entries(this.cookies)
			.map(([name, value]) => `${name}=${value}`)
			.join("; ");
	}

	async request(method, path, body) {
		const headers = { Accept: "application/json", Origin: ORIGIN };
		let bodyString;
		if (body !== undefined) {
			bodyString = JSON.stringify(body);
			headers["Content-Type"] = "application/json";
			headers["Content-Length"] = Buffer.byteLength(bodyString);
		}

		const cookieHeader = this.cookieHeader();
		if (cookieHeader) headers.Cookie = cookieHeader;

		const response = await rawRequest(method, path, headers, bodyString);
		const setCookies = response.headers["set-cookie"];
		if (Array.isArray(setCookies)) {
			for (const raw of setCookies) {
				const pair = raw.split(";")[0];
				const eq = pair.indexOf("=");
				if (eq === -1) continue;
				this.cookies[pair.slice(0, eq).trim()] = pair.slice(eq + 1).trim();
			}
		}

		let json = null;
		try {
			json = JSON.parse(response.body);
		} catch {
			json = null;
		}

		return {
			status: response.status,
			headers: response.headers,
			ok: response.status >= 200 && response.status < 300,
			json,
		};
	}
}

function assert(condition, message) {
	if (!condition) throw new Error(message);
}

const ONE_PIXEL_PNG_BASE64 =
	"iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAwMCAO8N7vEAAAAASUVORK5CYII=";

async function uploadPromotionImage(session, suffix) {
	const form = new FormData();
	form.append(
		"file",
		new Blob([Buffer.from(ONE_PIXEL_PNG_BASE64, "base64")], { type: "image/png" }),
		`promotion-cache-${suffix}.png`,
	);

	const headers = { Origin: ORIGIN };
	const cookieHeader = session.cookieHeader();
	if (cookieHeader) headers.Cookie = cookieHeader;

	const response = await fetch(`${ORIGIN}/api/admin/promotions/media/upload`, {
		method: "POST",
		headers,
		body: form,
	});

	let json = null;
	try {
		json = await response.json();
	} catch {
		json = null;
	}

	return {
		status: response.status,
		ok: response.ok,
		json,
	};
}

function isoNowPlusMinutes(minutes) {
	return new Date(Date.now() + minutes * 60_000).toISOString();
}

async function main() {
	await new Session().request("POST", "/api/dev/seed");

	const admin = new Session();
	const adminLogin = await admin.request("POST", "/api/auth/sign-in/email", {
		email: "admin@example.test",
		password: PASSWORD,
	});
	if (!adminLogin.ok) {
		throw new Error(`Failed to login admin: ${JSON.stringify(adminLogin.json)}`);
	}

	const customer = new Session();
	const customerLogin = await customer.request("POST", "/api/auth/sign-in/email", {
		email: "thandi@example.test",
		password: PASSWORD,
	});
	if (!customerLogin.ok) {
		throw new Error(`Failed to login customer: ${JSON.stringify(customerLogin.json)}`);
	}

	const uploadOne = await uploadPromotionImage(admin, "one");
	assert(uploadOne.ok, `Promotion image upload #1 failed: ${JSON.stringify(uploadOne.json)}`);
	const firstImageKey = uploadOne.json?.data?.imageKey;
	assert(
		typeof firstImageKey === "string" && firstImageKey.length > 0,
		`Upload #1 did not return imageKey: ${JSON.stringify(uploadOne.json)}`,
	);

	const createdPromotion = await admin.request("POST", "/api/admin/promotions", {
		title: `Promotion Cache Smoke ${STAMP}`,
		subtitle: "Cache header and replacement verification",
		description: "Generated by promotion-media-cache-smoke",
		imageKey: firstImageKey,
		startAt: isoNowPlusMinutes(-1),
		endAt: isoNowPlusMinutes(60 * 24),
		active: true,
		notifyCustomers: false,
		ctaText: "See menu",
		ctaUrl: "/app/menu",
	});
	assert(
		createdPromotion.ok,
		`Failed to create promotion: ${JSON.stringify(createdPromotion.json)}`,
	);
	const promotionId = createdPromotion.json?.data?.id;
	assert(typeof promotionId === "string" && promotionId.length > 0, "Missing promotion id");

	const publicImage = await new Session().request(
		"GET",
		`/api/media/public/promotions?key=${encodeURIComponent(firstImageKey)}`,
	);
	assert(publicImage.ok, `Public promotion image route failed with status ${publicImage.status}`);
	const publicCacheControl = String(publicImage.headers["cache-control"] ?? "");
	assert(
		publicCacheControl.includes("public") &&
			publicCacheControl.includes("max-age=31536000") &&
			publicCacheControl.includes("immutable"),
		`Unexpected promotion public cache-control: ${publicCacheControl}`,
	);
	const publicContentType = String(publicImage.headers["content-type"] ?? "");
	assert(
		publicContentType.startsWith("image/"),
		`Expected image content-type, got: ${publicContentType}`,
	);
	assert(Boolean(publicImage.headers.etag), "Expected etag on public promotion media response");

	const privateWithoutSession = await new Session().request(
		"GET",
		`/api/media/object?key=${encodeURIComponent(firstImageKey)}`,
	);
	assert(
		privateWithoutSession.status === 401,
		`Expected /api/media/object auth enforcement, got ${privateWithoutSession.status}`,
	);

	const privateWithCustomerSession = await customer.request(
		"GET",
		`/api/media/object?key=${encodeURIComponent(firstImageKey)}`,
	);
	assert(privateWithCustomerSession.ok, "Authenticated private promotion media request failed");
	const privateCacheControl = String(privateWithCustomerSession.headers["cache-control"] ?? "");
	assert(
		privateCacheControl.includes("private"),
		`Expected private cache-control for authenticated media route, got: ${privateCacheControl}`,
	);

	const uploadTwo = await uploadPromotionImage(admin, "two");
	assert(uploadTwo.ok, `Promotion image upload #2 failed: ${JSON.stringify(uploadTwo.json)}`);
	const secondImageKey = uploadTwo.json?.data?.imageKey;
	assert(
		typeof secondImageKey === "string" && secondImageKey.length > 0,
		`Upload #2 did not return imageKey: ${JSON.stringify(uploadTwo.json)}`,
	);
	assert(
		secondImageKey !== firstImageKey,
		"Expected replacement upload to generate a new image key",
	);

	const patchedPromotion = await admin.request(
		"PATCH",
		`/api/admin/promotions/${promotionId}`,
		{ imageKey: secondImageKey },
	);
	assert(
		patchedPromotion.ok,
		`Failed to patch promotion image: ${JSON.stringify(patchedPromotion.json)}`,
	);
	assert(
		patchedPromotion.json?.data?.imageKey === secondImageKey,
		"Promotion did not persist replacement image key",
	);

	const oldPublicAfterReplace = await new Session().request(
		"GET",
		`/api/media/public/promotions?key=${encodeURIComponent(firstImageKey)}`,
	);
	assert(
		oldPublicAfterReplace.status === 404,
		`Expected replaced promotion image key to be deleted, got ${oldPublicAfterReplace.status}`,
	);

	const home = await customer.request("GET", "/api/customer/home");
	assert(home.ok, `Failed to fetch customer home: ${JSON.stringify(home.json)}`);
	const activePromotions = home.json?.data?.activePromotions ?? [];
	const promotionOnHome = activePromotions.find((entry) => entry.id === promotionId);
	assert(
		promotionOnHome?.imageKey === secondImageKey,
		"Customer home did not return replacement promotion image key",
	);

	const removeImage = await admin.request(
		"PATCH",
		`/api/admin/promotions/${promotionId}`,
		{ imageKey: null },
	);
	assert(
		removeImage.ok,
		`Failed to remove promotion image: ${JSON.stringify(removeImage.json)}`,
	);
	assert(removeImage.json?.data?.imageKey === null, "Promotion image key was not removed");

	const secondPublicAfterRemove = await new Session().request(
		"GET",
		`/api/media/public/promotions?key=${encodeURIComponent(secondImageKey)}`,
	);
	assert(
		secondPublicAfterRemove.status === 404,
		`Expected removed promotion image key to be deleted, got ${secondPublicAfterRemove.status}`,
	);

	console.log("Promotion media cache smoke checks passed");
}

main().catch((error) => {
	console.error(error);
	process.exitCode = 1;
});
